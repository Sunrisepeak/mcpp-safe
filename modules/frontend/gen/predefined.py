#!/usr/bin/env python3
"""Writes modules/frontend/src/predefined.cppm: the macros the compiler predefines for each target MC++
builds for (MS: linux-x64, macos-arm64, windows-x64), as `mcxx c++ -target T -std=c++23 -dM -E -x c++
/dev/null` prints them -- what MC++'s preprocessor starts from, so that `#if defined(_WIN32)` means there
what it means to the compiler.

    python3 modules/frontend/gen/predefined.py PATH/TO/mcxx > modules/frontend/src/predefined.cppm
"""
import re, subprocess, sys

TARGETS = ["x86_64-unknown-linux-gnu", "aarch64-apple-darwin", "x86_64-pc-windows-msvc"]
mcxx = sys.argv[1]
version = subprocess.run([mcxx, "version", "--json"], capture_output=True, text=True).stdout


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


tables = []
for target in TARGETS:
    out = subprocess.run([mcxx, "c++", "-target", target, "-std=c++23", "-dM", "-E", "-x", "c++", "/dev/null"],
                         capture_output=True, text=True, check=True).stdout
    rows = []
    for line in out.splitlines():
        m = re.match(r"#define ([A-Za-z_][A-Za-z_0-9]*)(\([^)]*\))?(?: (.*))?$", line)
        if m:
            rows.append((m.group(1), m.group(2) or "", m.group(3) or ""))
    rows.sort()
    tables.append((target, rows))

import json
clang = json.loads(version)["compiler"]["version"]
print(f"""// Generated by modules/frontend/gen/predefined.py (Clang {clang}, -std=c++23, no other flags): do not edit.
//
// The macros the compiler predefines for each target MC++ builds for, name and replacement as
// `-dM -E` prints them; a function-like one has its parameter list, as written (`(c)`).
export module mcxx.frontend:predefined;

import std;

export namespace mcxx::frontend::predefined {{

struct Definition {{
    std::string_view name;
    std::string_view parameters;   // "" for an object-like macro
    std::string_view replacement;
}};

struct Table {{
    std::string_view target;
    std::span<const Definition> definitions;   // sorted by name
}};
""")
for i, (target, rows) in enumerate(tables):
    print(f"// {target}\ninline constexpr Definition TABLE_{i}[] {{")
    for name, parameters, value in rows:
        print(f"    {{ {quote(name)}, {quote(parameters)}, {quote(value)} }},")
    print("};\n")
print("inline constexpr Table TABLES[] {")
for i, (target, _) in enumerate(tables):
    print(f"    {{ {quote(target)}, TABLE_{i} }},")
print("};\n\n} // namespace mcxx::frontend::predefined")
