#!/usr/bin/env python3
"""Writes modules/frontend/src/unicode.cppm: which code points may start and continue an identifier
([lex.name]: XID_Start and XID_Continue, UAX #31, plus the mathematical notation profile Clang accepts
as an extension: ID_Compat_Math_Start and ID_Compat_Math_Continue, the characters P3658R1 adds), taken from the Clang release MC++'s lexer is checked against, so the two agree on the
Unicode version as well (Clang 23.1: Unicode 18.0).

    python3 modules/frontend/gen/unicode.py PATH/TO/clang/lib/Lex/UnicodeCharSets.h > modules/frontend/src/unicode.cppm

The file is llvm.clang-dev's source: .mcpp/.xlings/data/xpkgs/llvm-x-clang-dev/<version>/.../clang/lib/Lex/.
"""
import re, sys

source = open(sys.argv[1], encoding="utf-8").read()


def table(name):
    body = re.search(name + r"\[\]\s*=\s*\{(.*?)\n\s*\};", source, re.S).group(1)
    return [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}", body)]


version = re.search(r"// Unicode ([0-9.]+) XID_Start", source).group(1)
start = table("XIDStartRanges")
# XID_Continue in Clang's form excludes XID_Start; the file's own table is the whole property.
cont = sorted(table("XIDContinueRanges") + start)
math_start = table("MathematicalNotationProfileIDStartRanges")
math_cont = table("MathematicalNotationProfileIDContinueRanges")


def merge(ranges):
    out = []
    for a, b in sorted(ranges):
        if out and a <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], b))
        else:
            out.append((a, b))
    return out


def subtract(ranges, taken):
    """The code points of `ranges` not in `taken`."""
    out = []
    taken = merge(taken)
    for a, b in merge(ranges):
        for c, d in taken:
            if d < a or c > b:
                continue
            if c > a:
                out.append((a, c - 1))
            a = d + 1
            if a > b:
                break
        if a <= b:
            out.append((a, b))
    return out


# What only the mathematical notation profile gives (P3658R1): not XID_Start, and not XID_Continue.
math_only_start = subtract(math_start, start)
math_only_continue = subtract(math_cont + math_start, cont)


def emit(name, ranges):
    rows = [f"{{ 0x{a:05X}, 0x{b:05X} }}" for a, b in merge(ranges)]
    lines = [", ".join(rows[i:i + 6]) for i in range(0, len(rows), 6)]
    return f"constexpr Range {name}[] {{\n    " + ",\n    ".join(lines) + ",\n};\n"


print(f"""// Generated by modules/frontend/gen/unicode.py from Clang's UnicodeCharSets.h (Unicode {version}): do not edit.
//
// Which code points an identifier may start and continue with ([lex.name]): XID_Start and XID_Continue
// (UAX #31), and the mathematical notation profile's characters Clang accepts as an extension (∂, ∇,
// ∞ and their mathematical forms to start; superscript and subscript digits to continue); those of the
// profile alone are kept apart too (math_start, math_continue), for P3658R1.
export module mcxx.frontend:unicode;

import std;

namespace mcxx::frontend::unicode {{

struct Range {{
    char32_t first;
    char32_t last;
}};

{emit("START", start + math_start)}
{emit("CONTINUE", cont + math_start + math_cont)}
{emit("MATH_START", math_only_start)}
{emit("MATH_CONTINUE", math_only_continue)}
bool in(std::span<const Range> ranges, char32_t c) {{
    const auto it = std::ranges::lower_bound(ranges, c, {{}}, &Range::last);
    return it != ranges.end() && it->first <= c;
}}

}} // namespace mcxx::frontend::unicode

export namespace mcxx::frontend::unicode {{

// The Unicode version of the tables.
constexpr std::string_view VERSION {{ "{version}" }};

// A non-ASCII code point that may start an identifier.
bool identifier_start(char32_t c) {{ return in(START, c); }}

// A non-ASCII code point that may continue one (every one that may start one, too).
bool identifier_continue(char32_t c) {{ return in(CONTINUE, c); }}

// A code point only the mathematical notation profile lets an identifier start with (P3658R1; Clang
// takes it as an extension in every mode): it has ID_Compat_Math_Start, and not XID_Start.
bool math_start(char32_t c) {{ return in(MATH_START, c); }}

// One only that profile lets an identifier continue with: ID_Compat_Math_Continue (or _Start), and not
// XID_Continue.
bool math_continue(char32_t c) {{ return in(MATH_CONTINUE, c); }}

}} // namespace mcxx::frontend::unicode""")
